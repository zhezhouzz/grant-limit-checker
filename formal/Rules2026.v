(** 通用的数值与日期谓词。 *)
Definition 年份阈值2020 : nat := 2020.
Definition 年份阈值2023 : nat := 2023.
Definition 年份阈值2024 : nat := 2024.
Definition 费用阈值200万元 : nat := 200.
Definition 预算阈值400万元 : nat := 400.

Definition 日期早于 (年 月 日 : nat) (待判断项目 : 项目) : bool :=
  if Nat.ltb (执行期结束年份 待判断项目) 年 then true
  else if Nat.eqb (执行期结束年份 待判断项目) 年 then
    if Nat.ltb (执行期结束月份 待判断项目) 月 then true
    else if Nat.eqb (执行期结束月份 待判断项目) 月
         then Nat.ltb (执行期结束日 待判断项目) 日
         else false
  else false.

Definition 批准年份不早于2020 (待判断项目 : 项目) : bool :=
  Nat.leb 年份阈值2020 (批准年份 待判断项目).

Definition 批准年份不早于2023 (待判断项目 : 项目) : bool :=
  Nat.leb 年份阈值2023 (批准年份 待判断项目).

Definition 费用超过200万元 (待判断项目 : 项目) : bool :=
  Nat.ltb 费用阈值200万元 (直接费用万元 待判断项目).

Definition 中央财政预算不超过400万元 (待判断项目 : 项目) : bool :=
  Nat.leb (中央财政专项资金预算万元 待判断项目) 预算阈值400万元.

(** 基金委规则按“申请当年资助期满”判断。 *)
Definition 执行期结束不晚于申请年度 (申请年度 : nat) (待判断项目 : 项目) : bool :=
  Nat.leb (执行期结束年份 待判断项目) 申请年度.

Definition 申请年度仍在执行期内 (申请年度 : nat) (待判断项目 : 项目) : bool :=
  Nat.ltb 申请年度 (执行期结束年份 待判断项目).

(** 科技部两批 2026 指南使用精确的 2026-12-31 边界：只有早于该日结束
    的项目才不计入，因此 2026-12-31 当日结束的项目仍然计入。 *)
Definition 科技部2026截止日前结束 (待判断项目 : 项目) : bool :=
  日期早于 2026 12 31 待判断项目.

