  | 科技部2026数学物理人工智能五专项 =>
      match 项目角色值 待判断项目 with
      | 申请人 | 项目负责人 | 课题负责人 | 骨干成员 | 其他研究人员 => true | _ => false
      end
  | _ => false
  end.

Definition 科技部指南类别纳入内部总数 (拟申报项目 待判断项目 : 项目) : bool :=
  orb (属于国家重点研发或重大专项 待判断项目)
      (andb
        (match 指南版本值 拟申报项目 with
         | 科技部2026数学物理人工智能五专项 => true | _ => false end)
        (属于十一月指南扩展计划 待判断项目)).

Definition 项目应计入科技部内部总数 (拟申报项目 待判断项目 : 项目) : bool :=
  andb (科技部指南类别纳入内部总数 拟申报项目 待判断项目)
    (andb (科技部指南角色纳入内部总数 拟申报项目 待判断项目)
      (andb (negb (科技部小额国际合作不计内部总数 待判断项目))
        (andb
          (match 项目状态值 待判断项目, 项目角色值 待判断项目 with
           | 已退出, 其他研究人员 => false
           | _, _ => true
           end)
          (依指南仍在联合限项期内 2026 拟申报项目 待判断项目)))).

Definition 科技部内部项目总数 (拟申报项目 : 项目) (已有项目 : list 项目) : nat :=
  按条件计数 (项目应计入科技部内部总数 拟申报项目) 已有项目 +
  (if 项目应计入科技部内部总数 拟申报项目 拟申报项目 then 1 else 0).

Definition 退出国家科技计划执行期内不得申报
    (拟申报项目 : 项目) (已有项目 : list 项目) : bool :=
  andb (是已明确科技部2026指南 拟申报项目)
    (existsb
      (fun p =>
        andb (属于国家重点研发或重大专项 p)
          (andb
            (match 项目状态值 p with 已退出 => true | _ => false end)
            (andb
              (match 项目角色值 p with
               | 项目负责人 | 课题负责人 | 骨干成员 => true
               | _ => false
               end)
              (negb (科技部2026截止日前结束 p)))))
      已有项目).

(** 对尚未完整形式化的类别返回“需要人工复核”，而不是绿色的允许。 *)
Definition 基金委特殊规则需要复核 (拟申报项目 : 项目) : bool :=
  andb (属于基金委项目 拟申报项目)
    (match 项目类别值 拟申报项目 with
     | 面上项目 | 重大项目 => false
     | _ => true
     end).

Definition 复核原因列表 (拟申报项目 : 项目) : list 复核原因 :=
  (match 指南版本值 拟申报项目 with
   | 未指定科技部指南 => [科技部指南版本未指定]
   | _ => []
   end) ++
  (if 基金委特殊规则需要复核 拟申报项目
   then [基金委特殊规则尚未完整覆盖] else []).
