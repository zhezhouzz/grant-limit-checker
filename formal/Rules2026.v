(** NSFC-2026-GENERAL-1。同类型规则只约束“申请人”；这项显式判断修复了
    主要参与者被误当作同类型申请人的问题。联合基金名称和若干例外项目尚未
    细分，因此这些类别转入人工复核，不在这里贸然判定。 *)
Definition 同类申请规则适用 (拟申报项目 : 项目) : bool :=
  andb (属于基金委项目 拟申报项目)
    (andb (是申请人 (项目角色值 拟申报项目))
      (match 项目类别值 拟申报项目 with
       | 重大研究计划 | 联合基金 | 不计总数项目 => false
       | _ => true
       end)).

Definition 同类申请应计数 (拟申报项目 : 项目) (已有项目 : 项目) : bool :=
  andb (同类申请规则适用 拟申报项目)
    (andb (是申请阶段 已有项目)
      (andb (是申请人 (项目角色值 已有项目))
            (项目类别相同 (项目类别值 拟申报项目) (项目类别值 已有项目)))).

Definition 同类申请总数 (拟申报项目 : 项目) (已有项目 : list 项目) : nat :=
  let fix 计数 (项目列表 : list 项目) : nat :=
      match 项目列表 with
      | [] => 0
      | 当前项目 :: 其余项目 =>
          (if 同类申请应计数 拟申报项目 当前项目 then 1 else 0) + 计数 其余项目
      end in
  if 同类申请规则适用 拟申报项目 then 计数 已有项目 + 1 else 0.

(** NSFC-2026-GENERAL-2：先覆盖无需亚类信息即可准确判断的面上、重大和
    地区项目；重大研究计划和联合基金需要进一步输入亚类或基金名称。 *)
Definition 上年度获资助限制适用 (拟申报项目 : 项目) : bool :=
  andb (是申请人 (项目角色值 拟申报项目))
    (match 项目类别值 拟申报项目 with
     | 面上项目 | 重大项目 | 地区科学基金 => true
     | _ => false
     end).

Definition 是上年度同类获资助项目 (申请年度 : nat) (拟申报项目 已有项目 : 项目) : bool :=
  andb (上年度获资助限制适用 拟申报项目)
    (andb (项目类别相同 (项目类别值 拟申报项目) (项目类别值 已有项目))
      (andb (是项目负责人角色 (项目角色值 已有项目))
        (andb (是获资助记录 已有项目)
              (Nat.eqb (S (批准年份 已有项目)) 申请年度)))).

Definition 上年度获资助同类项目不得申请 (申请年度 : nat)
    (拟申报项目 : 项目) (已有项目 : list 项目) : bool :=
  existsb (是上年度同类获资助项目 申请年度 拟申报项目) 已有项目.

(** NSFC-2026-TOTAL-1。 *)
Definition 项目属于基金委总数范围 (待判断项目 : 项目) : bool :=
  match 项目类别值 待判断项目 with
  | 国家重点研发计划 | 国家科技重大专项
  | 中科院抢占科技制高点专项 | 国家实验室专项 => false
  | 不计总数项目 => false
  | 组织间国际合作 =>
      andb (费用超过200万元 待判断项目)
           (是负责人 (项目角色值 待判断项目))
  | 创新研究群体 => Nat.ltb 年份阈值2024 (批准年份 待判断项目)
  | _ => true
  end.

Definition 基金委申请阶段应计入总数 (待判断项目 : 项目) : bool :=
  match 项目类别值 待判断项目, 项目状态值 待判断项目 with
  | 青年A类, 申请中 | 青年B类, 申请中
  | 创新研究群体, 申请中 | 卓越研究群体, 申请中
  | 原创探索长期, 申请中 => false
  | 原创探索长期, 已正式受理 | 原创探索长期, 评审中 => false
  | _, 申请中 | _, 已正式受理 | _, 评审中 => true
  | _, _ => false
  end.

Definition 在研参与项目应计数 (人员 : 人员情况) (待判断项目 : 项目) : bool :=
  match 当前职称 人员 with
  | 高级职称 =>
      match 批准时职称 待判断项目 with
      | 非高级职称 => false
      | 高级职称 => 批准年份不早于2020 待判断项目
      end
  | 非高级职称 => 批准年份不早于2023 待判断项目
  end.

Definition 是基金委负责人角色 (r : 项目角色) : bool :=
  match r with 申请人 | 项目负责人 | 学术带头人 => true | _ => false end.

Definition 是基金委参与者角色 (r : 项目角色) : bool :=
  match r with 主要参与者 | 骨干成员 => true | _ => false end.

Definition 项目应计入总数 (人员 : 人员情况) (申请年度 : nat)
    (待判断项目 : 项目) : bool :=
  andb (项目属于基金委总数范围 待判断项目)
    (match 项目状态值 待判断项目 with
     | 申请中 | 已正式受理 | 评审中 => 基金委申请阶段应计入总数 待判断项目
     | 正在承担 | 已退出 =>
         andb (申请年度仍在执行期内 申请年度 待判断项目)
           (if 是基金委负责人角色 (项目角色值 待判断项目)
            then true else 在研参与项目应计数 人员 待判断项目)
     | 初审不予受理 | 未获资助 | 已经结题 => false
     end).

Definition 应计入负责人总数 (人员 : 人员情况) (申请年度 : nat)
    (待判断项目 : 项目) : bool :=
  andb (项目应计入总数 人员 申请年度 待判断项目)
       (是基金委负责人角色 (项目角色值 待判断项目)).

Definition 应计入参与者总数 (人员 : 人员情况) (申请年度 : nat)
    (待判断项目 : 项目) : bool :=
  andb (项目应计入总数 人员 申请年度 待判断项目)
       (是基金委参与者角色 (项目角色值 待判断项目)).

Fixpoint 按条件计数 (条件 : 项目 -> bool) (项目列表 : list 项目) : nat :=
  match 项目列表 with
  | [] => 0
  | 当前项目 :: 其余项目 =>
      (if 条件 当前项目 then 1 else 0) + 按条件计数 条件 其余项目
  end.

Definition 项目总数 (人员 : 人员情况) (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : nat :=
