  (if 项目应计入总数 人员 申请年度 拟申报项目 then 1 else 0).

Definition 负责人项目总数 (人员 : 人员情况) (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : nat :=
  按条件计数 (应计入负责人总数 人员 申请年度) 已有项目 +
  (if 应计入负责人总数 人员 申请年度 拟申报项目 then 1 else 0).

Definition 参与者项目总数 (人员 : 人员情况) (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : nat :=
  按条件计数 (应计入参与者总数 人员 申请年度) 已有项目 +
  (if 应计入参与者总数 人员 申请年度 拟申报项目 then 1 else 0).

(** JOINT-2022-107。联合限项的到期边界由本次所选指南决定。 *)
Definition 科技部重点研发标识纳入联合限项 (待判断项目 : 项目) : bool :=
  match 项目标识值 待判断项目 with
  | 青年科学家标识 | 科技型中小企业标识 | 国际合作类标识
  | 政府间国际合作标识 | 战略性港澳台合作标识 => false
  | _ => true
  end.

Definition 科技重大专项标识纳入联合限项 (待判断项目 : 项目) : bool :=
  match 项目标识值 待判断项目 with 青年科学家标识 => false | _ => true end.

Definition 联合限项类别与角色匹配 (人员 : 人员情况) (待判断项目 : 项目) : bool :=
  match 项目类别值 待判断项目 with
  | 重大项目 => 是项目或课题负责人 (项目角色值 待判断项目)
  | 卓越研究群体 => 是学术带头人或骨干成员 (项目角色值 待判断项目)
  | 重大科研仪器 =>
      andb
        (match 项目标识值 待判断项目 with 部门推荐标识 => true | _ => false end)
        (orb (是负责人 (项目角色值 待判断项目))
             (andb
               (match 当前职称 人员 with 高级职称 => true | 非高级职称 => false end)
               (是主要参与者 (项目角色值 待判断项目))))
  | 国家重点研发计划 =>
      andb (科技部重点研发标识纳入联合限项 待判断项目)
           (是项目或课题负责人 (项目角色值 待判断项目))
  | 国家科技重大专项 =>
      andb (科技重大专项标识纳入联合限项 待判断项目)
           (是项目或课题负责人 (项目角色值 待判断项目))
  | _ => false
  end.

Definition 依指南仍在联合限项期内 (申请年度 : nat) (拟申报项目 待判断项目 : 项目) : bool :=
  match 项目状态值 待判断项目 with
  | 申请中 | 已正式受理 | 评审中 => true
  | 正在承担 | 已退出 =>
      if 是已明确科技部2026指南 拟申报项目
      then negb (科技部2026截止日前结束 待判断项目)
      else 申请年度仍在执行期内 申请年度 待判断项目
  | 初审不予受理 | 未获资助 | 已经结题 => false
  end.

Definition 项目应计入联合限项 (人员 : 人员情况) (申请年度 : nat)
    (拟申报项目 待判断项目 : 项目) : bool :=
  andb (依指南仍在联合限项期内 申请年度 拟申报项目 待判断项目)
       (联合限项类别与角色匹配 人员 待判断项目).

Definition 联合限项项目总数 (人员 : 人员情况) (申请年度 : nat)
    (拟申报项目 : 项目) (已有项目 : list 项目) : nat :=
  按条件计数 (项目应计入联合限项 人员 申请年度 拟申报项目) 已有项目 +
  (if 项目应计入联合限项 人员 申请年度 拟申报项目 拟申报项目 then 1 else 0).

