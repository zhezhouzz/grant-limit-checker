Theorem 高级职称总数超限诊断可靠 :
  forall 人员 申请年度 拟申报项目 已有项目,
    当前职称 人员 = 高级职称 ->
    In 高级职称总数超限
       (基金委总数违规列表 人员 申请年度 拟申报项目 已有项目) ->
    2 < 项目总数 人员 申请年度 拟申报项目 已有项目.
Proof.
  intros 人员 申请年度 拟申报项目 已有项目 当前为高级职称 出现超限诊断.
  unfold 基金委总数违规列表 in 出现超限诊断.
  destruct (属于基金委项目 拟申报项目); [| contradiction].
  rewrite 当前为高级职称 in 出现超限诊断.
  destruct (Nat.leb (项目总数 人员 申请年度 拟申报项目 已有项目) 2)
    eqn:总数未超限.
  - contradiction.
  - apply Nat.leb_gt in 总数未超限. exact 总数未超限.
Qed.

Theorem 允许判定不含违规 :
  forall 人员 申请年度 拟申报项目 已有项目,
    检查 人员 申请年度 拟申报项目 已有项目 = 允许 ->
    违规列表 人员 申请年度 拟申报项目 已有项目 = [].
Proof.
  intros 人员 申请年度 拟申报项目 已有项目 判定为允许.
  unfold 检查 in 判定为允许.
  destruct (违规列表 人员 申请年度 拟申报项目 已有项目); [reflexivity | discriminate].
Qed.

