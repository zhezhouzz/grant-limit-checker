From Stdlib Require Import List Arith Bool.
From GrantLimit Require Import Model Rules2026.
Import ListNotations.

Definition 同类申请违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if 同类申请规则适用 拟申报项目 then
    if Nat.leb (同类申请总数 拟申报项目 已有项目) 1
    then [] else [同年同类申请超限]
  else [].

Definition 上年度获资助违规列表 (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if 上年度获资助同类项目不得申请 申请年度 拟申报项目 已有项目
  then [上年度获资助同类项目受限]
  else [].

Definition 基金委总数违规列表 (人员 : 人员情况) (申请年度 : nat)
    (拟申报项目 : 项目) (已有项目 : list 项目) : list 违规原因 :=
  if 属于基金委项目 拟申报项目 then
    match 当前职称 人员 with
    | 高级职称 =>
        if Nat.leb (项目总数 人员 申请年度 拟申报项目 已有项目) 2
        then [] else [高级职称总数超限]
    | 非高级职称 =>
        (if Nat.leb (负责人项目总数 人员 申请年度 拟申报项目 已有项目) 1
         then [] else [非高级职称负责人超限]) ++
        (if Nat.leb (参与者项目总数 人员 申请年度 拟申报项目 已有项目) 2
         then [] else [非高级职称参与者超限])
    end
  else [].

Definition 联合限项违规列表 (人员 : 人员情况) (申请年度 : nat)
    (拟申报项目 : 项目) (已有项目 : list 项目) : list 违规原因 :=
  if 项目应计入联合限项 人员 申请年度 拟申报项目 拟申报项目 then
    if Nat.leb (联合限项项目总数 人员 申请年度 拟申报项目 已有项目) 2
    then [] else [国家科技计划联合限项超限]
  else [].

Definition 科学仪器联合限项违规列表 (人员 : 人员情况) (申请年度 : nat)
    (拟申报项目 : 项目) (已有项目 : list 项目) : list 违规原因 :=
  if 是科学仪器联合限项项目 拟申报项目 then
    if Nat.leb (科学仪器联合限项总数 人员 申请年度 拟申报项目 已有项目) 1
    then [] else [科学仪器项目联合限项超限]
  else [].

Definition 科技部同期负责人申报违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if andb (是已明确科技部2026指南 拟申报项目)
           (科技部负责人申报应计数 拟申报项目) then
    if Nat.leb (科技部同期负责人申报总数 拟申报项目 已有项目) 1
    then [] else [国家科技计划同期负责人申报超限]
  else [].

Definition 在研项目负责人违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if 在研国家科技计划项目负责人不得再次申报 拟申报项目 已有项目
  then [国家科技计划在研项目负责人申报受限]
  else [].

Definition 在研课题负责人违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if 在研课题负责人不得再次牵头 拟申报项目 已有项目
  then [国家科技计划在研课题负责人牵头受限]
  else [].

Definition 科技部内部总数违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if andb (是已明确科技部2026指南 拟申报项目)
           (项目应计入科技部内部总数 拟申报项目 拟申报项目) then
    if Nat.leb (科技部内部项目总数 拟申报项目 已有项目) 2
    then [] else [国家科技计划人员总数超限]
  else [].

Definition 退出项目违规列表 (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  if 退出国家科技计划执行期内不得申报 拟申报项目 已有项目
  then [退出国家科技计划执行期内申报受限]
  else [].

Definition 违规列表 (人员 : 人员情况) (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : list 违规原因 :=
  同类申请违规列表 拟申报项目 已有项目 ++
  上年度获资助违规列表 申请年度 拟申报项目 已有项目 ++
  基金委总数违规列表 人员 申请年度 拟申报项目 已有项目 ++
  联合限项违规列表 人员 申请年度 拟申报项目 已有项目 ++
  科学仪器联合限项违规列表 人员 申请年度 拟申报项目 已有项目 ++
  科技部同期负责人申报违规列表 拟申报项目 已有项目 ++
  在研项目负责人违规列表 拟申报项目 已有项目 ++
  在研课题负责人违规列表 拟申报项目 已有项目 ++
  科技部内部总数违规列表 拟申报项目 已有项目 ++
  退出项目违规列表 拟申报项目 已有项目.

Definition 检查 (人员 : 人员情况) (申请年度 : nat) (拟申报项目 : 项目)
    (已有项目 : list 项目) : 判定结果 :=
  match 违规列表 人员 申请年度 拟申报项目 已有项目 with
  | _ :: _ => 阻止
  | [] =>
      match 复核原因列表 拟申报项目 with
      | [] => 允许
      | _ :: _ => 需要人工复核
      end
  end.
